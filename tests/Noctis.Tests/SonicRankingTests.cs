using FreeMusicFinder;
using Xunit;

namespace Noctis.Tests;

public sealed class SonicRankingTests : IDisposable
{
    private readonly string _folder = Path.Combine(Path.GetTempPath(), "noctis-sonic-" + Guid.NewGuid().ToString("N"));
    public void Dispose() { if (Directory.Exists(_folder)) Directory.Delete(_folder, true); }
    private static SonicVector V(float x, float y, string model = "test-v1", string domain = "preview") =>
        SonicVector.Create(model, domain, new[] { x, y, 0f, 0, 0, 0, 0, 0 })!;

    [Fact] public void BadVectorsAreIgnoredAndSpacesNeverMix()
    {
        Assert.Null(SonicVector.Create("m", "preview", Enumerable.Repeat(float.NaN, 8)));
        Assert.Null(SonicVector.Create("m", "preview", new float[8]));
        Assert.Null(V(1, 0).Similarity(V(1, 0, "other")));
        Assert.Null(V(1, 0).Similarity(V(1, 0, domain: "local")));
        Assert.Equal(1, V(2, 0).Similarity(V(1, 0))!.Value, 6);
    }

    [Fact] public void MultimodalTasteUsesNeighboursNotOneAverageOrTheCandidateItself()
    {
        SonicExample[] taste = [new("a", V(1, 0), 1), new("b", V(0.9f, 0.1f), 2), new("c", V(-1, 0), 1), new("d", V(-.9f, -.1f), 1)];
        Assert.True(SonicRanking.Affinity("new", V(1, 0), taste) > SonicRanking.Affinity("new", V(0, 1), taste));
        Assert.Null(SonicRanking.Affinity("a", V(1, 0), taste.Take(2).ToList()));
        Assert.Null(SonicRanking.Affinity("new", V(1, 0, domain: "local"), taste));
    }

    [Fact] public void MissingVectorsKeepBaselineAndBlendIsBounded()
    {
        CatalogSong Song(string title) => new(title, title, [new("artist", "Artist")], 200, true);
        CatalogSong[] songs = [Song("a"), Song("b"), Song("c"), Song("missing")];
        var vectors = songs.Take(3).Select((s, i) => (DiscoverIdentity.Key(s), V(1-i, i))).ToDictionary(x => x.Item1, x => x.Item2);
        SonicExample[] taste = [new("liked1", V(1, 0), 1), new("liked2", V(.9f, .1f), 1)];
        var m = SonicRanking.Multipliers(songs, vectors, taste, 500);
        Assert.DoesNotContain(DiscoverIdentity.Key(songs[3]), m.Keys);
        Assert.All(m.Values, v => Assert.InRange(v, Math.Exp(-.5), Math.Exp(.5)));
        Assert.Empty(SonicRanking.Multipliers(songs, vectors, taste, 0));
    }

    [Fact] public void CacheIsVersionedDomainSpecificAndCorruptionIsAMiss()
    {
        var cache = new SonicCache(_folder, "test-v1");
        cache.Write("song", "deezer:1", V(1, 0));
        Assert.NotNull(cache.Read("song", "deezer:1"));
        Assert.Null(cache.Read("song", "deezer:2"));
        Assert.Null(cache.Read("song", "deezer:1", "local"));
        Assert.Null(new SonicCache(_folder, "test-v2").Read("song", "deezer:1"));
        File.WriteAllText(Directory.GetFiles(_folder).Single(), "not json");
        Assert.Null(cache.Read("song", "deezer:1"));
    }

    [Fact] public void NativeFrontendMatchesTransformersGoldenIncludingReflectedEdges()
    {
        // Transformers 4.57.6 ClapFeatureExtractor, pinned clap-htsat-unfused config. 440 Hz at .2 amplitude.
        // Values are a captured independent reference, not generated by the implementation under test.
        var wave = Enumerable.Range(0, 480000).Select(i => (float)(.2 * Math.Sin(2 * Math.PI * i * 440 / 48000))).ToArray();
        var features = SonicClapFeatures.Extract(wave);
        int[] bins = [0, 5, 10, 15, 20, 30, 40, 50, 63];
        (int Frame, double[] Expected)[] reference = [
            (0, [.669199, 13.467700, -.391578, -10.230094, -16.052488, -26.485025, -36.504414, -45.870895, -56.775024]),
            (1, [-42.065132, 8.479688, -28.760075, -47.832096, -54.800003, -66.743515, -76.833282, -86.150810, -97.133400]),
            (500, [-45.524242, 8.479962, -29.150990, -52.725651, -64.888893, -83.765755, -99.967644, -100, -100]),
            (1000, [.655656, 13.657486, -.409074, -10.245384, -16.066858, -26.499552, -36.518909, -45.885387, -56.789558]),
        ];
        foreach (var row in reference)
            for (int i = 0; i < bins.Length; i++) Assert.InRange(features[row.Frame * 64 + bins[i]], row.Expected[i] - .01, row.Expected[i] + .01);
    }
}
